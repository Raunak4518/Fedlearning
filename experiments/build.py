"""
experiments/build.py

Builds one standalone, single-file script per experiment:

    experiments/E00_paper_parity.py = core.py + specs/E00_paper_parity.py

Each built file needs only PyTorch, torchvision and NumPy, so it can be
copied alone to Kaggle, Colab or a lab machine and run:

    python E03_method_components.py --quick        # viability check, minutes
    python E03_method_components.py                # full run, 3 seeds
    python E03_method_components.py --list         # planned runs

Edit core.py or a spec, then rerun:  python experiments/build.py
"""
import glob
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    core = open(os.path.join(HERE, "core.py"), encoding="utf-8").read()
    for spec_path in sorted(glob.glob(os.path.join(HERE, "specs", "E*.py"))):
        name = os.path.splitext(os.path.basename(spec_path))[0]
        spec = open(spec_path, encoding="utf-8").read()
        doc_end = spec.index('"""', 3) + 3
        doc, body = spec[:doc_end], spec[doc_end:]
        out = (f"#!/usr/bin/env python3\n{doc}\n"
               f"# GENERATED by experiments/build.py from core.py + specs/{name}.py; edit those.\n\n"
               f"{core}\n\n# {'=' * 70}\n#  Experiment definition\n# {'=' * 70}\n{body.strip()}\n\n\n"
               f"if __name__ == \"__main__\":\n    main(EXPERIMENT)\n")
        with open(os.path.join(HERE, f"{name}.py"), "w", encoding="utf-8", newline="\n") as f:
            f.write(out)
        print("built", name)


if __name__ == "__main__":
    main()
