"""Checks the pre-registered predictions E1-E4 of experiments/fedembed.py and writes summary.md next to runs.jsonl.
Usage: python experiments/fedembed_analysis.py results/E40_fedembed_mf [results/E41_fedembed_lm]"""
import glob, json, os, sys
import numpy as np

ARMS = ["adam_l2", "adam_l2_reset", "adamw", "adam", "adam_l2_hwa", "sgd_l2", "central_l2"]
NAMES = {"adam_l2": "Adam + L2 (coupled), FedAvg", "adam_l2_reset": "Adam + L2, state reset each round",
         "adamw": "AdamW (decoupled), FedAvg", "adam": "Adam, no decay, FedAvg",
         "adam_l2_hwa": "Adam + L2, rows averaged over holders (HWA)", "sgd_l2": "SGD + L2, FedAvg",
         "central_l2": "centralised Adam + L2"}


def load(folder):
    rows = []
    for f in sorted(glob.glob(os.path.join(folder, "**", "runs.jsonl"), recursive=True)):
        rows += [json.loads(l) for l in open(f)]
    seen, out = set(), []
    for r in rows:  # later files win on duplicates
        key = (r["arm"], r["K"], r["seed"])
        if key in seen:
            out = [x for x in out if (x["arm"], x["K"], x["seed"]) != key]
        seen.add(key)
        out.append(r)
    return out


def m(xs):
    xs = [x for x in xs if x is not None]
    return (np.mean(xs), np.std(xs, ddof=1) if len(xs) > 1 else 0.0, len(xs)) if xs else (float("nan"), 0.0, 0)


def main(folder):
    R = load(folder)
    task = R[0]["task"]
    met, metr = ("rmse", "rmse_kappa_lt1") if task == "mf" else ("ppl", "ppl_rare_ctx")
    Ks = sorted({r["K"] for r in R if r["arm"] != "central_l2"})
    L = [f"# {os.path.basename(folder)}: rare-row collapse in federated embedding models ({task})", "",
         "Generated by `experiments/fedembed_analysis.py` from `runs.jsonl`. Mean over seeds (n). "
         "A row is collapsed when its final norm is <= 0.15 of its initial norm; kappa from client counts (paper §3.5).", ""]
    for K in Ks:
        L += [f"## K = {K}", "",
              f"| arm | n | rows with kappa < 1 | collapsed among them | median norm (kappa < 1 / >= 1) | Spearman(log kappa, norm) "
              f"| {met} | {metr} (contexts / items with kappa < 1) |", "|---|---|---|---|---|---|---|---|"]
        for arm in ARMS:
            rs = [r for r in R if r["arm"] == arm and (r["K"] == K or arm == "central_l2")]
            if not rs:
                continue
            lo = m([r["n_kappa_lt1"] for r in rs])[0]
            col = m([r["collapsed_kappa_lt1"] for r in rs])[0]
            L.append(f"| {NAMES[arm]} | {len(rs)} | {lo:.0f} | {col:.0f} ({100 * col / max(lo, 1):.1f}%) | "
                     f"{m([r['median_norm_kappa_lt1'] for r in rs])[0]:.3f} / {m([r['median_norm_kappa_ge1'] for r in rs])[0]:.3f} | "
                     f"{m([r['spearman_logkappa_norm'] for r in rs])[0]:.2f} | {m([r[met] for r in rs])[0]:.3f} | "
                     f"{m([r[metr] for r in rs])[0]:.3f} |")
        L.append("")
    bins = [0, 0.25, 0.5, 0.75, 1, 2, 4, 8, np.inf]
    L += ["## Final / initial row norm by kappa (median over rows; all K and seeds pooled)", "",
          "| arm | " + " | ".join(f"{bins[i]}-{bins[i + 1]}" for i in range(len(bins) - 1)) + " | no non-holder |",
          "|---|" + "---|" * len(bins)]
    for arm in ARMS:
        rs = [r for r in R if r["arm"] == arm]
        if not rs:
            continue
        k = np.concatenate([[np.inf if x is None else x for x in r["kappa"]] for r in rs])
        n = np.concatenate([r["norm_ratio"] for r in rs])
        cells = []
        for i in range(len(bins) - 1):
            sel = (k >= bins[i]) & (k < bins[i + 1])
            cells.append(f"{np.median(n[sel]):.2f} ({sel.sum()})" if sel.any() else "-")
        sel = ~np.isfinite(k)
        cells.append(f"{np.median(n[sel]):.2f} ({sel.sum()})" if sel.any() else "-")
        L.append(f"| {NAMES[arm]} | " + " | ".join(cells) + " |")
    L.append("")
    L += ["## Pre-registered predictions", ""]
    a = [r for r in R if r["arm"] == "adam_l2"]
    e1 = all(r["collapsed_kappa_lt1"] == r["n_kappa_lt1"] for r in a)
    sp = m([r["spearman_logkappa_norm"] for r in a])[0]
    L.append(f"- E1 (every kappa < 1 row collapses under Adam + L2; Spearman >= 0.8): "
             f"{sum(r['collapsed_kappa_lt1'] for r in a)} of {sum(r['n_kappa_lt1'] for r in a)} rows collapsed; "
             f"largest final norm among them {max(r['max_norm_kappa_lt1'] for r in a):.3f}; mean Spearman {sp:.2f} -> "
             f"{'HOLDS' if e1 and sp >= 0.8 else 'FAILS'}")
    others = [r for r in R if r["arm"] in ("adamw", "adam", "adam_l2_hwa", "central_l2")]
    e2 = sum(r["collapsed_kappa_lt1"] for r in others)
    L.append(f"- E2 (no kappa < 1 row collapses under AdamW, Adam without decay, HWA or centralised): "
             f"{e2} collapsed rows in {len(others)} runs -> {'HOLDS' if e2 == 0 else 'FAILS'}")
    e3 = []
    for K in Ks:
        for ref in ("adamw", "adam_l2_hwa"):
            x = {r["seed"]: r[metr] for r in R if r["arm"] == "adam_l2" and r["K"] == K}
            y = {r["seed"]: r[metr] for r in R if r["arm"] == ref and r["K"] == K}
            d = [x[s] - y[s] for s in x if s in y and x[s] is not None and y[s] is not None]
            if d:
                e3.append((K, ref, np.mean(d), len(d)))
    L.append("- E3 (worse error on kappa < 1 items / contexts under Adam + L2 than under AdamW and HWA, every K): " +
             "; ".join(f"K={K} vs {ref}: {d:+.3f} (n={n})" for K, ref, d, n in e3) +
             f" -> {'HOLDS' if e3 and all(d > 0 for _, _, d, _ in e3) else 'FAILS'}")
    frac = [(K, m([r["collapsed_kappa_lt1"] + r["collapsed_kappa_ge1"] for r in a if r["K"] == K])[0] / a[0]["n_rows" if task == "lm" else "n_items"])
            for K in Ks]
    L.append("- E4 (fraction of collapsed rows grows with K): " + ", ".join(f"K={K}: {f:.3f}" for K, f in frac) +
             f" -> {'HOLDS' if all(frac[i][1] < frac[i + 1][1] for i in range(len(frac) - 1)) else 'FAILS'}")
    open(os.path.join(folder, "summary.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    for f in sys.argv[1:]:
        main(f)
