"""Experiment ledger: every run already done, and a duplicate check for planned jobs.

    python ledger.py                      # writes experiments/LEDGER.md
    python ledger.py --check K14_kaggle_ablation_seeds_mcb [--datasets mnist ...]
        lists which planned runs of a built script already exist in results/ (run nothing twice)

A run is identified by (method, dataset, IF, alpha, K, seed). Folders with runs.jsonl
match on the exact method spec; summary-only folders (Kaggle results pasted back) match
on the label, and their seeds are taken as 0 .. n-1 (every K job uses seeds 0, 1, 2 unless
its notebook passed --seeds).
"""
import argparse
import glob
import importlib
import json
import os
import re
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")


def setting(ds, IF, alpha, K):
    a = "None" if alpha in (None, "None") else float(alpha)
    return (ds, float(IF), a, int(K))


def mkey(m):
    return json.dumps(m, sort_keys=True)


def load_runs():
    """-> list of dicts: folder, label, method key or None, setting, seed."""
    runs = []
    for d in sorted(glob.glob(os.path.join(RES, "*/"))):
        folder = os.path.basename(d.rstrip("/"))
        jl = os.path.join(d, "runs.jsonl")
        sm = os.path.join(d, "summary.md")
        if os.path.exists(jl):
            for line in open(jl, encoding="utf-8"):
                r = json.loads(line)
                # T03-style diagnostic records carry no setting fields: they ran at IF=0.01, Dir(0.5), K=10
                # with a reduced schedule (quick_scale < 1), so they count as quick passes.
                runs.append(dict(folder=folder, label=r["label"], method=mkey(r.get("method")),
                                 setting=setting(r["dataset"], r.get("IF", 0.01), r.get("alpha", 0.5), r.get("K", 10)),
                                 seed=int(r["seed"]),
                                 quick=bool(r.get("quick", False)) or folder.endswith("_quick")
                                 or r.get("quick_scale", 1.0) < 1.0))
        elif os.path.exists(sm):
            cur = None
            for line in open(sm, encoding="utf-8"):
                h = re.match(r"## (\w+)\s+IF=([\d.]+)\s+alpha=(\S+)\s+K=(\d+)", line)
                if h:
                    cur, first_table = setting(*h.groups()), True
                    continue
                if cur and line.startswith("| label | n |"):
                    in_table = True
                    continue
                m = re.match(r"\| (.+?) \| (\d+) \| [\d.]+ ±", line)
                if cur and m:
                    for s in range(int(m.group(2))):
                        runs.append(dict(folder=folder, label=m.group(1), method=None, setting=cur, seed=s,
                                         quick=folder.endswith("_quick")))
    return runs


def write_ledger(runs, path):
    by = defaultdict(lambda: defaultdict(set))
    for r in runs:
        tag = r["folder"] + (" (quick)" if r["quick"] and not r["folder"].endswith("_quick") else "")
        by[r["setting"]][(r["label"], tag)].add(r["seed"])
    lines = ["# Experiment ledger (generated by `python experiments/ledger.py`; do not edit by hand)", "",
             "Every completed run in `experiments/results/`, by setting. **Before writing a new job, run "
             "`python experiments/ledger.py --check <script>` so nothing is run twice.** "
             "`_quick` folders are reduced-round viability passes, not full runs.", ""]
    for st in sorted(by, key=lambda s: (s[0], -s[1], str(s[2]), s[3])):
        ds, IF, a, K = st
        lines += [f"## {ds}  IF={IF}  alpha={a}  K={K}", "", "| label | result folder | seeds |", "|---|---|---|"]
        for (lab, tag), seeds in sorted(by[st].items()):
            lines.append(f"| {lab} | {tag} | {','.join(map(str, sorted(seeds)))} |")
        lines.append("")
    lines += job_status(runs)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", path, f"({len(runs)} runs)")


def _flat(d, pre=""):
    out = {}
    for k, v in (d or {}).items():
        if isinstance(v, dict):
            out.update(_flat(v, pre + k + "."))
        else:
            out[pre + k] = v
    return out


def same_method(stored, plan_m, defaults):
    """stored (from an older runs.jsonl) matches the planned method if every stored key agrees
    and every key the stored dict lacks (added to the code later) is at its 'off' default."""
    a, b = _flat(stored), _flat(plan_m)
    for k, v in b.items():
        if k in a:
            if a[k] != v:
                return False
        elif defaults.get(k, v) != v:
            return False
    return True


def planned(script, argv):
    """The runs a built script would execute with these command-line arguments."""
    sys.path.insert(0, HERE)
    import build
    if os.path.exists(os.path.join(HERE, "specs", script + ".py")):
        build.build_one(script)                  # built scripts are untracked; regenerate from core + spec
    saved = sys.argv
    sys.argv = [script] + argv
    try:
        mod = importlib.import_module(script)
    finally:
        sys.argv = saved
    exp = mod.EXPERIMENT
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, nargs="+")
    ap.add_argument("--datasets", nargs="+")
    ap.add_argument("--IF", type=float, nargs="+")
    ap.add_argument("--K", type=int, nargs="+")
    ap.add_argument("--only", nargs="+")
    a, _ = ap.parse_known_args(argv)
    cfg = dict(quick=False, seeds=a.seeds or exp.get("seeds", [0, 1, 2]), quick_scale=1.0, quick_frac={})
    plan = exp["plan"](cfg)
    planned.defaults = _flat(dict(fe=getattr(mod, "FE_DEFAULTS", {}), gen=getattr(mod, "GEN_DEFAULTS", {}),
                                  head=getattr(mod, "HEAD_DEFAULTS", {})))
    return [r for r in plan if (not a.datasets or r["dataset"] in a.datasets) and (not a.IF or r["IF"] in a.IF)
            and (not a.K or r["K"] in a.K) and (not a.only or r["label"] in a.only)]


def _seeds(xs):
    return ",".join(map(str, sorted(xs)))


def job_status(runs):
    """Every Kaggle notebook job and every local E/F spec: planned runs vs runs in its result folder."""
    import shlex
    sys.path.insert(0, HERE)
    import make_kaggle_notebooks as M
    done = defaultdict(set)                      # folder -> {(label, setting, seed)}
    meth = defaultdict(list)                     # (folder, setting, seed) -> [stored method dicts]
    for r in runs:
        done[r["folder"]].add((r["label"], r["setting"], r["seed"]))
        if r["method"]:
            meth[(r["folder"], r["setting"], r["seed"])].append(json.loads(r["method"]))
    jobs = [(j[0], j[1], shlex.split(j[2]), j[3]) for j in M.JOBS]
    for spec in sorted(glob.glob(os.path.join(HERE, "specs", "[EF]*.py"))):
        name = os.path.splitext(os.path.basename(spec))[0]
        if os.path.exists(os.path.join(HERE, name + ".py")):
            jobs.append(("(local)", name, [], name))
    lines = ["## Status of every job (planned runs vs runs in its result folder)", "",
             "COMPLETE = every planned run is in the folder. PARTIAL lists the missing (label: seeds). "
             "NOT RUN = no result folder (ask before re-running: the zip may just not be copied back). "
             "QUICK ONLY = only a reduced-round viability pass exists. "
             "Most PARTIAL rows are arms added to a spec AFTER it ran (superseded by a later job); see "
             "docs/PROGRESS.md before re-running any of them.", "",
             "| job | script + args | result folder | planned | done | status |", "|---|---|---|---|---|---|"]
    for nb, script, argv, folder in jobs:
        try:
            plan = planned(script, argv)
        except Exception as e:  # pragma: no cover
            lines.append(f"| {nb} | {script} | {folder} | ? | ? | cannot plan: {e} |")
            continue
        folders = [f for f in done if f == folder or f.startswith(folder + "__")]
        have = set().union(*[done[f] for f in folders]) if folders else set()
        miss = defaultdict(set)
        for r in plan:
            key = (r["label"], setting(r["dataset"], r["IF"], r["alpha"], r["K"]), r["seed"])
            by_method = any(same_method(m, r["m"], planned.defaults)
                            for f in folders for m in meth.get((f, key[1], key[2]), []))
            if key not in have and not by_method:
                miss[(r["label"], key[1])].add(r["seed"])
        n_miss = sum(len(v) for v in miss.values())
        if not folders:
            status = "QUICK ONLY" if folder + "_quick" in done else "NOT RUN"
        elif n_miss == 0:
            status = "COMPLETE"
        else:
            status = "PARTIAL - missing " + "; ".join(f"{lab} {st[0]} IF={st[1]} K={st[3]}: s{_seeds(sd)}"
                                                       for (lab, st), sd in sorted(miss.items()))
        args = " ".join(argv)
        lines.append(f"| {nb} | {script} {args} | {', '.join(folders) or folder} | {len(plan)} | "
                     f"{len(plan) - n_miss} | {status} |")
    return lines + [""]


def check(script, argv, runs):
    plan = planned(script, argv)
    by_m = defaultdict(list)
    by_l = defaultdict(list)
    for r in runs:
        if r["quick"]:
            continue
        if r["method"]:
            by_m[(r["method"], r["setting"], r["seed"])].append(r)
        by_l[(r["label"], r["setting"], r["seed"])].append(r)
    dup = 0
    for r in plan:
        st = setting(r["dataset"], r["IF"], r["alpha"], r["K"])
        hit = by_m.get((mkey(r["m"]), st, r["seed"])) or by_l.get((r["label"], st, r["seed"]))
        if hit:
            dup += 1
        print(("DUPLICATE " if hit else "new       ") + f"{r['label']} | {st} | s{r['seed']}"
              + (f"   <- already in {sorted({h['folder'] for h in hit})}" if hit else ""))
    print(f"\n{dup} of {len(plan)} planned runs already exist.")


if __name__ == "__main__":
    if len(sys.argv) > 2 and sys.argv[1] == "--check":
        check(sys.argv[2], sys.argv[3:], load_runs())
    else:
        write_ledger(load_runs(), os.path.join(HERE, "LEDGER.md"))
